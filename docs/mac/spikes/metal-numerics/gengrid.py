# Writes grid.inc, the tables of the codebook kernels in numerics.metal: kvalues_iq4nl (ggml-common.h) and the
# first 512 and 1024 u64 values of splitmix64 from seed 1. numerics.mm builds the same tables.
M = (1 << 64) - 1
KV = [-127, -104, -83, -65, -49, -35, -22, -10, 1, 13, 25, 38, 53, 69, 89, 113]
x = 1
vals = []
for _ in range(1024):
    x = (x + 0x9E3779B97F4A7C15) & M
    z = x
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M
    vals.append(z ^ (z >> 31))
print('// generated by gengrid.py')
print('constexpr constant char kKv[16] = {%s};' % ', '.join(map(str, KV)))
for name, n in (('kGrid', 512), ('kGrid1k', 1024)):
    print('constexpr constant ulong %s[%d] = {' % (name, n))
    for i in range(0, n, 4):
        print('    ' + ', '.join('0x%016xul' % v for v in vals[i:i + 4]) + ',')
    print('};')
